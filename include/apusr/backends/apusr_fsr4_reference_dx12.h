class Dx12Fsr4ReferenceRuntime {
public:
    virtual ~Dx12Fsr4ReferenceRuntime() = default;

    [[nodiscard]] virtual Status initialize(const Dx12Fsr4ReferenceCreateDesc& desc) = 0;
    [[nodiscard]] virtual Status planFrame(const Dx12Fsr4ReferenceFrameDesc& desc, Dx12Fsr4ReferenceBackendPlan& outPlan) = 0;

    // Prepares device-local runtime state that does not depend on borrowed
    // per-frame resources. Frontends should call this outside the command-list
    // hot path when they can predict the initial preset/permutation, so first
    // gameplay dispatches do not pay PSO/resource/upload-ring creation costs.
    [[nodiscard]] virtual Status prepareFrameCache(const Dx12Fsr4ReferenceFrameDesc& desc) = 0;

    // Records the native DX12 reference dispatch sequence when a real command
    // list is supplied.  Planning/resource tests may still call it without a
    // command list, in which case the backend prepares cached runtime state but
    // does not emit native commands.
    [[nodiscard]] virtual Status recordFrame(const Dx12Fsr4ReferenceFrameDesc& desc) = 0;
};

