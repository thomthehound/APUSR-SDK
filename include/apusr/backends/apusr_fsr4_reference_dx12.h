// Backend-side plan for the real FSR4 INT8 DX12 reference runner.  This is the
// seam between the API-neutral model graph and the actual DX12 recorder: it is
// allowed to speak in shader profiles, descriptor ranges, and upload buffers,
// but it intentionally does not expose this structure back into frontend code.
enum class Dx12Fsr4ReferenceShaderProviderKind : std::uint32_t {
    PackagedCache,
    EmbeddedCache,
    RuntimeCompile,
};

struct Dx12Fsr4ReferenceShaderProviderConfig {
    // Performance-first default: use precompiled shader bytecode only.  Product
    // FFX-compatible DLL builds embed the complete DX12 reference shader product
    // matrix so the drop-in artifact does not need a repo/build-side cache.  A
    // packaged cache is still supported for CI/developer overrides.  Runtime
    // compilation is deliberately opt-in and should remain a developer/debug
    // path, not the end-user hot path.
    bool enablePackagedCache = true;
    bool enableEmbeddedCache = true;
    bool allowRuntimeCompilation = false;
    bool requireCompletePrecompiledCache = true;

    // Optional fail-loud developer/experiment guard.  Dispatches listed here
    // must resolve from the packaged cache.  They are not allowed to fall back
    // to any embedded product table, which prevents an experiment run from
    // silently testing a different shader after a bad cache path.
    std::vector<std::string> requiredPackagedDispatches;

    std::string packagedCacheRoot;
};

struct Dx12Fsr4ReferenceCreateDesc {
    NativeHandle device;
    std::string repoRoot;
    models::fsr4_int8::ReferenceRunnerCreateDesc runner;
    Dx12Fsr4ReferenceShaderProviderConfig shaderProvider;

    // Optional startup/package validation input.  The manifest is generated by
    // tools/model/generate_fsr4_reference_shader_resource_manifest.py.  Its
    // schema is shared with future backends; this DX12 backend consumes only
    // targetApi=dx12 entries and parses it once at initialization, never during
    // dispatch recording.
    std::string reflectionManifestPath;
    bool enableReflectionManifestValidation = false;
    bool requireCompleteReflectionCoverage = false;
    bool requireInitializerBytes = true;
};

inline constexpr std::uint64_t kDx12Fsr4ReferenceUnknownNativeResourceState = UINT64_MAX;

struct Dx12Fsr4ReferenceExternalResources {
    // Borrowed per-frame frontend resources.  The backend treats these as
    // externally owned and never releases or reallocates them.  Missing
    // exposure is legal when the frame plan resolves InputExposure to the
    // internal default-exposure resource.
    NativeHandle inputColor;
    NativeHandle inputDepth;
    NativeHandle inputMotionVectors;
    NativeHandle inputExposure;
    NativeHandle output;

    // Frontend-provided resource formats for borrowed resources.  These are
    // intentionally API-neutral SurfaceFormat values rather than DXGI_FORMATs;
    // the DX12 backend uses them together with the actual ID3D12Resource
    // description to create compatible SRV/UAV views.  This mirrors the FFX
    // backend behavior more closely than blindly using the model's preferred
    // semantic format for game-owned resources.
    SurfaceFormat inputColorFormat = SurfaceFormat::Unknown;
    SurfaceFormat inputDepthFormat = SurfaceFormat::Unknown;
    SurfaceFormat inputMotionVectorsFormat = SurfaceFormat::Unknown;
    SurfaceFormat inputExposureFormat = SurfaceFormat::Unknown;
    SurfaceFormat outputFormat = SurfaceFormat::Unknown;

    // Opaque native D3D12_RESOURCE_STATES values for borrowed resources at the
    // point APUSR starts recording.  They intentionally stay as integers in the
    // public seam so the model/planning layer remains API-neutral and Vulkan can
    // use the same manifest/binding concepts later.  Unknown/omitted values are
    // normalized to COMMON by the DX12 backend.
    std::uint64_t inputColorState = kDx12Fsr4ReferenceUnknownNativeResourceState;
    std::uint64_t inputDepthState = kDx12Fsr4ReferenceUnknownNativeResourceState;
    std::uint64_t inputMotionVectorsState = kDx12Fsr4ReferenceUnknownNativeResourceState;
    std::uint64_t inputExposureState = kDx12Fsr4ReferenceUnknownNativeResourceState;
    std::uint64_t outputState = kDx12Fsr4ReferenceUnknownNativeResourceState;

    // Off by default for the product path: the frontend/host-capture layer should
    // decide whether borrowed resources need to be restored for a particular
    // integration.  Turning this on preserves correctness for command-list
    // borrowing probes without baking restore barriers into every normal frame.
    bool restoreExternalResourceStatesAfterDispatch = false;
};

struct Dx12Fsr4ReferenceFrameDesc {
    NativeHandle commandList;

    // Optional native D3D12 direct queue.  It is only used by opt-in GPU
    // timestamp diagnostics to convert timestamp ticks to time.  Recording the
    // frame still works without it; the profiler will emit raw ticks only.
    NativeHandle commandQueue;
    models::fsr4_int8::ReferenceRunnerFrameDesc runner;
    Dx12Fsr4ReferenceExternalResources externalResources;
};

