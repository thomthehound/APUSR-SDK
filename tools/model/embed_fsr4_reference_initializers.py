from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

PRESETS = ["quality", "balanced", "performance", "ultraperf", "native", "drs"]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Embed FSR4 INT8 reference initializer payloads into C++.")
    parser.add_argument("--repo-root", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--verify", action="store_true")
    return parser.parse_args()


def c_array_initializer(data: bytes) -> str:
    lines: list[str] = []
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return "\n".join(lines)


def load_payloads(repo_root: Path) -> list[tuple[str, bytes, str]]:
    root = repo_root / "models" / "fsr4_int8" / "reference" / "fsr4_4_0_2_int8"
    payloads: list[tuple[str, bytes, str]] = []
    for preset in PRESETS:
        path = root / preset / "initializers.bin"
        if not path.is_file():
            raise SystemExit(f"missing FSR4 reference initializer payload: {path}")
        data = path.read_bytes()
        if not data:
            raise SystemExit(f"empty FSR4 reference initializer payload: {path}")
        payloads.append((preset, data, hashlib.sha256(data).hexdigest()))
    return payloads


def write_header(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// Copyright (c) 2026 thomthehound.\n"
        "// Auto-generated by tools/model/embed_fsr4_reference_initializers.py.\n"
        "\n"
        "#pragma once\n"
        "\n"
        "#include <apusr/models/apusr_fsr4_int8_graph.h>\n"
        "\n"
        "#include <cstddef>\n"
        "#include <cstdint>\n"
        "\n"
        "namespace apusr::models::fsr4_int8::embedded_initializers {\n"
        "\n"
        "struct InitializerBlob {\n"
        "    Preset preset = Preset::Balanced;\n"
        "    const char* presetName = nullptr;\n"
        "    const std::uint8_t* data = nullptr;\n"
        "    std::size_t size = 0;\n"
        "    const char* sha256 = nullptr;\n"
        "\n"
        "    [[nodiscard]] constexpr bool available() const noexcept { return data != nullptr && size != 0; }\n"
        "};\n"
        "\n"
        "[[nodiscard]] const InitializerBlob* find(Preset preset) noexcept;\n"
        "\n"
        "} // namespace apusr::models::fsr4_int8::embedded_initializers\n",
        encoding="utf-8",
    )

def write_source(path: Path, header_include: str, payloads: list[tuple[str, bytes, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    parts: list[str] = [
        "// SPDX-License-Identifier: MIT\n",
        "// Copyright (C) 2025 Advanced Micro Devices, Inc.\n",
        "// Copyright (c) 2026 thomthehound.\n",
        "// Derived payload from the MIT-licensed FidelityFX SDK 2.0.0 / FSR 4.0.2 reference material.\n",
        "// Auto-generated by tools/model/embed_fsr4_reference_initializers.py.\n\n",
        f"#include <{header_include}>\n\n",
        "#include <array>\n\n",
        "namespace apusr::models::fsr4_int8::embedded_initializers {\n\n",
    ]
    for preset, data, sha in payloads:
        symbol = preset.replace("-", "_")
        parts.append(f"namespace {{\nconst std::array<std::uint8_t, {len(data)}> k_{symbol}_initializers = {{\n")
        parts.append(c_array_initializer(data))
        parts.append("\n};\n")
        parts.append(f"constexpr char k_{symbol}_sha256[] = \"{sha}\";\n}} // namespace\n\n")
    parts.append("const InitializerBlob* find(const Preset preset) noexcept\n{\n")
    parts.append("    static constexpr InitializerBlob kBlobs[] = {\n")
    enum_map = {
        "quality": "Quality",
        "balanced": "Balanced",
        "performance": "Performance",
        "ultraperf": "UltraPerformance",
        "native": "NativeAA",
        "drs": "DynamicResolution",
    }
    for preset, data, sha in payloads:
        symbol = preset.replace("-", "_")
        parts.append(
            f"        {{Preset::{enum_map[preset]}, \"{preset}\", k_{symbol}_initializers.data(), k_{symbol}_initializers.size(), k_{symbol}_sha256}},\n"
        )
    parts.append("    };\n")
    parts.append("    for (const InitializerBlob& blob : kBlobs) {\n")
    parts.append("        if (blob.preset == preset) {\n")
    parts.append("            return &blob;\n")
    parts.append("        }\n")
    parts.append("    }\n")
    parts.append("    return nullptr;\n")
    parts.append("}\n\n")
    parts.append("} // namespace apusr::models::fsr4_int8::embedded_initializers\n")
    path.write_text("".join(parts), encoding="utf-8")


def main() -> None:
    args = parse_args()
    repo_root = args.repo_root.resolve()
    header = args.header.resolve()
    source = args.source.resolve()
    payloads = load_payloads(repo_root)
    if args.verify:
        import tempfile

        with tempfile.TemporaryDirectory(prefix="apusr_fsr4_init_embed_verify_") as temp_name:
            temp = Path(temp_name)
            generated_header = temp / header.name
            generated_source = temp / source.name
            write_header(generated_header)
            write_source(generated_source, "apusr/generated/apusr_fsr4_reference_initializers.h", payloads)
            if header.read_text(encoding="utf-8") != generated_header.read_text(encoding="utf-8"):
                raise SystemExit("embedded FSR4 reference initializer header is stale")
            if source.read_text(encoding="utf-8") != generated_source.read_text(encoding="utf-8"):
                raise SystemExit("embedded FSR4 reference initializer source is stale")
        return
    write_header(header)
    write_source(source, "apusr/generated/apusr_fsr4_reference_initializers.h", payloads)
    print(f"[fsr4-initializers] embedded {len(payloads)} preset initializer payload(s)")


if __name__ == "__main__":
    main()
