"""Emit a host-buildable token skeleton for the FSR4 middle-core tile array.

The generated code is not an AIE kernel. It is the first full-array programming
shape: stage functions, skip taps, token cadence, and a driver that proves the
whole NPU-owned graph consumes and produces the expected token counts. Real AIE
kernels should replace the stage bodies while preserving the contract unless a
measured better topology replaces this one.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CONTRACT = REPO_ROOT / "models" / "fsr4_int8" / "planning" / "middle_core_contracts" / "balanced__2160" / "middle_core_contract.json"
DEFAULT_OUT = REPO_ROOT / "out" / "middle_core_token_skeleton" / "balanced__2160"
BEATS_PER_TOKEN = 32


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def safe_ident(text: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in text).strip("_")


def pass_name(stage: dict[str, Any]) -> str:
    return f"stage{int(stage['pass']):02d}_{safe_ident(stage['kind'])}"


def cadence_expr(cadence: dict[str, Any], key: str) -> int:
    ratio = cadence[key]
    if int(ratio["den"]) != 1:
        raise ValueError(f"expected integer {key}, got {ratio}")
    return int(ratio["num"])


def emit_header() -> str:
    return f'''// SPDX-License-Identifier: Apache-2.0
// Copyright (c) 2026 thomthehound.
// Generated by tools/gen/gen_middle_core_token_skeleton.py.

#pragma once

#include <cstdint>
#include <stdexcept>
#include <string>

constexpr int kBeatsPerToken = {BEATS_PER_TOKEN};

struct TokenStream {{
    std::string name;
    std::uint64_t available_tokens = 0;
    std::uint64_t read_tokens = 0;
    std::uint64_t written_tokens = 0;

    explicit TokenStream(const char* stream_name) : name(stream_name) {{}}
}};

inline std::uint64_t read_token(TokenStream& stream) {{
    if (stream.available_tokens == 0) {{
        throw std::runtime_error("stream underflow: " + stream.name);
    }}
    --stream.available_tokens;
    ++stream.read_tokens;
    return stream.read_tokens;
}}

inline void write_token(TokenStream& stream, std::uint64_t) {{
    ++stream.available_tokens;
    ++stream.written_tokens;
}}

inline void copy_token(TokenStream& input, TokenStream& output) {{
    const std::uint64_t value = read_token(input);
    write_token(output, value);
}}

inline void copy_token_with_tap(TokenStream& input, TokenStream& output, TokenStream& tap) {{
    const std::uint64_t value = read_token(input);
    write_token(output, value);
    write_token(tap, value);
}}
'''


def emit_stage(stage: dict[str, Any], skip_sources: dict[int, str]) -> str:
    p = int(stage["pass"])
    name = pass_name(stage)
    kind = stage["kind"]
    cadence = stage["token_cadence"]
    output_tokens = int(cadence["output_tokens"])
    primary_per_output = cadence["primary_per_output"]
    output_per_primary = cadence["output_per_primary"]
    has_skip_input = stage.get("skip") is not None
    skip_tap = skip_sources.get(p)

    args = ["TokenStream& primary", "TokenStream& output"]
    if has_skip_input:
        args.insert(1, "TokenStream& skip")
    if skip_tap:
        args.append(f"TokenStream& {skip_tap}")

    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Copyright (c) 2026 thomthehound.",
        "// Generated by tools/gen/gen_middle_core_token_skeleton.py.",
        "",
        '#include "apusr_middle_core_stream_io.h"',
        "",
        f"void {name}({', '.join(args)}) {{",
        f"    // pass {p}: {stage['op_fn']} ({kind}), output tokens={output_tokens}",
    ]

    if kind in {"same_scale", "downsample_k2s2"}:
        consume_count = cadence_expr(cadence, "primary_per_output")
        lines.append(f"    for (int output_token = 0; output_token < {output_tokens}; ++output_token) {{")
        if skip_tap:
            lines.append("        const std::uint64_t first_value = read_token(primary);")
            for _ in range(consume_count - 1):
                lines.append("        (void)read_token(primary);")
            lines.append("        write_token(output, first_value);")
            lines.append(f"        write_token({skip_tap}, first_value);")
        else:
            lines.append("        const std::uint64_t first_value = read_token(primary);")
            for _ in range(consume_count - 1):
                lines.append("        (void)read_token(primary);")
            lines.append("        write_token(output, first_value);")
        lines.append("    }")
    elif kind == "upsample_ct2d_add":
        produce_per_primary = cadence_expr(cadence, "output_per_primary")
        lines.append(f"    for (int primary_token = 0; primary_token < {int(cadence['primary_tokens'])}; ++primary_token) {{")
        lines.append("        const std::uint64_t primary_value = read_token(primary);")
        lines.append(f"        for (int repeat = 0; repeat < {produce_per_primary}; ++repeat) {{")
        lines.append("            const std::uint64_t skip_value = read_token(skip);")
        lines.append("            write_token(output, primary_value ^ skip_value);")
        lines.append("        }")
        lines.append("    }")
    else:
        raise ValueError(f"unsupported middle-core skeleton stage kind: {kind}")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def emit_driver(contract: dict[str, Any], stage_names: list[str], skip_sources: dict[int, str]) -> str:
    stages = contract["stages"]
    prototypes = []
    for stage, name in zip(stages, stage_names):
        args = ["TokenStream& primary", "TokenStream& output"]
        if stage.get("skip") is not None:
            args.insert(1, "TokenStream& skip")
        if int(stage["pass"]) in skip_sources:
            args.append(f"TokenStream& {skip_sources[int(stage['pass'])]}")
        prototypes.append(f"void {name}({', '.join(args)});")

    ingress_tokens = int(contract["ingress"]["tensor"]["total_tokens"])
    egress_tokens = int(contract["egress"]["tensor"]["total_tokens"])
    skip_streams = {fifo["name"]: fifo for fifo in contract["skip_fifos"]}

    stream_names = ["ingress"] + [f"s{p:02d}" for p in range(1, 13)] + list(skip_streams)
    stream_decls = "\n".join(f'    TokenStream {name}("{name}");' for name in stream_names)
    skip_checks = "\n".join(
        f'    expect_empty({name});\n    expect_written({name}, {int(fifo["total_tokens_per_frame"])});'
        for name, fifo in skip_streams.items()
    )

    calls = [
        "    stage01_same_scale(ingress, s01);",
        "    stage02_same_scale(s01, s02, skipA);",
        "    stage03_downsample_k2s2(s02, s03);",
        "    stage04_same_scale(s03, s04);",
        "    stage05_same_scale(s04, s05, skipB);",
        "    stage06_downsample_k2s2(s05, s06);",
        "    stage07_same_scale(s06, s07);",
        "    stage08_same_scale(s07, s08);",
        "    stage09_upsample_ct2d_add(s08, skipB, s09);",
        "    stage10_same_scale(s09, s10);",
        "    stage11_upsample_ct2d_add(s10, skipA, s11);",
        "    stage12_same_scale(s11, s12);",
    ]

    return f'''// SPDX-License-Identifier: Apache-2.0
// Copyright (c) 2026 thomthehound.
// Generated by tools/gen/gen_middle_core_token_skeleton.py.

#include "apusr_middle_core_stream_io.h"

#include <iostream>

{chr(10).join(prototypes)}

static void expect_empty(const TokenStream& stream) {{
    if (stream.available_tokens != 0) {{
        throw std::runtime_error(stream.name + " left tokens unread");
    }}
}}

static void expect_written(const TokenStream& stream, std::uint64_t expected) {{
    if (stream.written_tokens != expected) {{
        throw std::runtime_error(stream.name + " wrote an unexpected token count");
    }}
}}

int main() {{
{stream_decls}

    ingress.available_tokens = {ingress_tokens};
{chr(10).join(calls)}

    expect_empty(ingress);
    expect_written(s12, {egress_tokens});
    if (s12.available_tokens != {egress_tokens}) {{
        throw std::runtime_error("egress token count mismatch");
    }}
{skip_checks}

    std::cout << "middle-core token skeleton PASS: {contract['permutation']} ingress={ingress_tokens} egress={egress_tokens}\\n";
    return 0;
}}
'''


def emit(contract_path: Path, out_dir: Path) -> None:
    contract = load_json(contract_path)
    skip_sources = {int(fifo["src_pass"]): fifo["name"] for fifo in contract["skip_fifos"]}
    out_dir.mkdir(parents=True, exist_ok=True)
    write(out_dir / "apusr_middle_core_stream_io.h", emit_header())

    stage_names = []
    for stage in contract["stages"]:
        name = pass_name(stage)
        stage_names.append(name)
        write(out_dir / f"{name}.cpp", emit_stage(stage, skip_sources))
    write(out_dir / "middle_core_token_skeleton.cpp", emit_driver(contract, stage_names, skip_sources))
    write(out_dir / "contract_path.txt", str(contract_path.resolve()) + "\n")
    print(out_dir)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--contract", type=Path, default=DEFAULT_CONTRACT, help="middle_core_contract.json")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="generated C++ skeleton output directory")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    emit(args.contract, args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
