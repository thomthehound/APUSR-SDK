inline ApusrFramegenSurfaceFormat apusrFramegenSurfaceFormatFromFfx(FfxApiSurfaceFormat format) noexcept
{
    return static_cast<ApusrFramegenSurfaceFormat>(format);
}

inline FfxApiSurfaceFormat apusrFramegenSurfaceFormatToFfx(ApusrFramegenSurfaceFormat format) noexcept
{
    return static_cast<FfxApiSurfaceFormat>(format);
}

inline ApusrFramegenResourceDescription apusrFramegenResourceDescriptionFromFfx(const FfxApiResourceDescription& description) noexcept
{
    return {
        static_cast<ApusrFramegenResourceType>(description.type),
        static_cast<ApusrFramegenSurfaceFormat>(description.format),
        description.width,
        description.height,
        description.depth,
        description.mipCount,
        description.flags,
        description.usage,
    };
}

inline FfxApiResourceDescription apusrFramegenResourceDescriptionToFfx(const ApusrFramegenResourceDescription& description) noexcept
{
    FfxApiResourceDescription result{};
    result.type = static_cast<std::uint32_t>(description.type);
    result.format = static_cast<std::uint32_t>(description.format);
    result.width = description.width;
    result.height = description.height;
    result.depth = description.depth;
    result.mipCount = description.mipCount;
    result.flags = description.flags;
    result.usage = description.usage;
    return result;
}

inline ApusrFramegenExternalResource apusrFramegenResourceFromFfx(const FfxApiResource& resource) noexcept
{
    return {
        resource.resource,
        apusrFramegenResourceDescriptionFromFfx(resource.description),
        static_cast<ApusrFramegenResourceState>(resource.state),
    };
}

inline FfxApiResource apusrFramegenResourceToFfx(const ApusrFramegenExternalResource& resource) noexcept
{
    FfxApiResource result{};
    result.resource = resource.resource;
    result.description = apusrFramegenResourceDescriptionToFfx(resource.description);
    result.state = static_cast<std::uint32_t>(resource.state);
    return result;
}
