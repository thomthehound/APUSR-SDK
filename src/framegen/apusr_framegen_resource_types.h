enum ApusrFramegenResourceType : std::uint32_t {
    APUSR_FRAMEGEN_RESOURCE_TYPE_BUFFER,
    APUSR_FRAMEGEN_RESOURCE_TYPE_TEXTURE1D,
    APUSR_FRAMEGEN_RESOURCE_TYPE_TEXTURE2D,
    APUSR_FRAMEGEN_RESOURCE_TYPE_TEXTURE_CUBE,
    APUSR_FRAMEGEN_RESOURCE_TYPE_TEXTURE3D,
};

using ApusrFramegenResourceUsage = std::uint32_t;
enum ApusrFramegenResourceUsageBits : std::uint32_t {
    APUSR_FRAMEGEN_RESOURCE_USAGE_READ_ONLY = 0,
    APUSR_FRAMEGEN_RESOURCE_USAGE_RENDERTARGET = 1u << 0,
    APUSR_FRAMEGEN_RESOURCE_USAGE_UAV = 1u << 1,
    APUSR_FRAMEGEN_RESOURCE_USAGE_DEPTHTARGET = 1u << 2,
    APUSR_FRAMEGEN_RESOURCE_USAGE_INDIRECT = 1u << 3,
    APUSR_FRAMEGEN_RESOURCE_USAGE_ARRAYVIEW = 1u << 4,
    APUSR_FRAMEGEN_RESOURCE_USAGE_STENCILTARGET = 1u << 5,
    APUSR_FRAMEGEN_RESOURCE_USAGE_DCC_RENDERTARGET = 1u << 15,
};

enum ApusrFramegenResourceState : std::uint32_t {
    APUSR_FRAMEGEN_RESOURCE_STATE_COMMON = 1u << 0,
    APUSR_FRAMEGEN_RESOURCE_STATE_UNORDERED_ACCESS = 1u << 1,
    APUSR_FRAMEGEN_RESOURCE_STATE_COMPUTE_READ = 1u << 2,
    APUSR_FRAMEGEN_RESOURCE_STATE_PIXEL_READ = 1u << 3,
    APUSR_FRAMEGEN_RESOURCE_STATE_PIXEL_COMPUTE_READ =
        APUSR_FRAMEGEN_RESOURCE_STATE_PIXEL_READ | APUSR_FRAMEGEN_RESOURCE_STATE_COMPUTE_READ,
    APUSR_FRAMEGEN_RESOURCE_STATE_COPY_SRC = 1u << 4,
    APUSR_FRAMEGEN_RESOURCE_STATE_COPY_DEST = 1u << 5,
    APUSR_FRAMEGEN_RESOURCE_STATE_GENERIC_READ =
        APUSR_FRAMEGEN_RESOURCE_STATE_COPY_SRC | APUSR_FRAMEGEN_RESOURCE_STATE_COMPUTE_READ,
    APUSR_FRAMEGEN_RESOURCE_STATE_INDIRECT_ARGUMENT = 1u << 6,
    APUSR_FRAMEGEN_RESOURCE_STATE_PRESENT = 1u << 7,
    APUSR_FRAMEGEN_RESOURCE_STATE_RENDER_TARGET = 1u << 8,
    APUSR_FRAMEGEN_RESOURCE_STATE_DEPTH_ATTACHMENT = 1u << 9,
};

using ApusrFramegenResourceFlags = std::uint32_t;
enum ApusrFramegenResourceFlagBits : std::uint32_t {
    APUSR_FRAMEGEN_RESOURCE_FLAGS_NONE = 0,
    APUSR_FRAMEGEN_RESOURCE_FLAGS_ALIASABLE = 1u << 0,
    APUSR_FRAMEGEN_RESOURCE_FLAGS_UNDEFINED = 1u << 1,
};

enum ApusrFramegenHeapType : std::uint32_t {
    APUSR_FRAMEGEN_HEAP_DEFAULT = 0,
    APUSR_FRAMEGEN_HEAP_UPLOAD,
    APUSR_FRAMEGEN_HEAP_READBACK,
};

enum ApusrFramegenFilter : std::uint32_t {
    APUSR_FRAMEGEN_FILTER_MINMAGMIP_POINT = 0,
    APUSR_FRAMEGEN_FILTER_MINMAGMIP_LINEAR,
    APUSR_FRAMEGEN_FILTER_MINMAGLINEARMIP_POINT,
};

enum ApusrFramegenAddressMode : std::uint32_t {
    APUSR_FRAMEGEN_ADDRESS_WRAP = 0,
    APUSR_FRAMEGEN_ADDRESS_MIRROR,
    APUSR_FRAMEGEN_ADDRESS_CLAMP,
    APUSR_FRAMEGEN_ADDRESS_BORDER,
    APUSR_FRAMEGEN_ADDRESS_MIRROR_ONCE,
};

struct ApusrFramegenResourceDescription {
    ApusrFramegenResourceType type = APUSR_FRAMEGEN_RESOURCE_TYPE_BUFFER;
    ApusrFramegenSurfaceFormat format = APUSR_FRAMEGEN_SURFACE_FORMAT_UNKNOWN;
    union {
        std::uint32_t width = 0;
        std::uint32_t size;
    };
    union {
        std::uint32_t height = 0;
        std::uint32_t stride;
    };
    union {
        std::uint32_t depth = 0;
        std::uint32_t alignment;
    };
    std::uint32_t mipCount = 0;
    ApusrFramegenResourceFlags flags = APUSR_FRAMEGEN_RESOURCE_FLAGS_NONE;
    ApusrFramegenResourceUsage usage = APUSR_FRAMEGEN_RESOURCE_USAGE_READ_ONLY;
};

struct ApusrFramegenExternalResource {
    void* resource = nullptr;
    ApusrFramegenResourceDescription description{};
    ApusrFramegenResourceState state = APUSR_FRAMEGEN_RESOURCE_STATE_COMMON;
    const void* backendMetadata = nullptr;
};
